package dev.cptgummiball.omacore.client;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.logging.LogUtils;
import dev.cptgummiball.omacore.OmaCore;
import java.io.Reader;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import net.minecraft.ChatFormatting;
import net.minecraft.Util;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import net.minecraft.util.FormattedCharSequence;
import org.lwjgl.glfw.GLFW;
import org.slf4j.Logger;

/**
 * Grandma's credits: a scrolling, bilingual text with the pack logo, the story's epilogue, the people, every mod and
 * its authors (assets/oma_core/texts/credits/&lt;de_de|en_us&gt;.json, generated by scripts/gen_credits.py).
 * Space or a held mouse button scrolls faster, Esc closes; the screen closes itself at the end.
 */
public final class CreditsScreen extends Screen {
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final ResourceLocation LOGO = ResourceLocation.fromNamespaceAndPath(OmaCore.MOD_ID,
            "textures/gui/credits_logo.png");
    private static final int LOGO_SIZE = 96;
    private static final float PIXELS_PER_TICK = 0.6f;
    private static final float FAST = 6f;

    private record Row(String type, List<FormattedCharSequence> text, int height) {
    }

    private final List<Row> rows = new ArrayList<>();
    private int totalHeight;
    private float scroll;
    private long lastMillis;
    private boolean fastKey;
    private boolean fastMouse;

    public CreditsScreen() {
        super(Component.translatable("oma_core.credits.title"));
    }

    @Override
    protected void init() {
        rows.clear();
        totalHeight = 0;
        int wrap = Math.min(width - 40, 340);
        for (JsonElement el : load()) {
            JsonObject o = el.getAsJsonObject();
            String type = o.get("type").getAsString();
            String text = o.has("text") ? o.get("text").getAsString() : "";
            Row row = switch (type) {
                case "logo" -> new Row(type, List.of(), LOGO_SIZE + 6);
                case "gap" -> new Row(type, List.of(), 12 * (o.has("size") ? o.get("size").getAsInt() : 1));
                case "title" -> lines(type, Component.literal(text).withStyle(ChatFormatting.GOLD, ChatFormatting.BOLD),
                        wrap / 2, 22);
                case "subtitle" -> lines(type, Component.literal(text).withStyle(ChatFormatting.YELLOW, ChatFormatting.ITALIC),
                        wrap, 12);
                case "story" -> lines(type, Component.literal(text).withStyle(s -> s.withColor(0xE8DCC8).withItalic(true)),
                        wrap, 12);
                case "heading" -> lines(type, Component.literal(text).withStyle(ChatFormatting.YELLOW), wrap, 13);
                case "mod" -> {
                    MutableComponent c = Component.literal(o.get("name").getAsString()).withStyle(ChatFormatting.WHITE)
                            .append(Component.literal("  " + o.get("by").getAsString()).withStyle(ChatFormatting.GRAY));
                    yield lines(type, c, wrap, 11);
                }
                default -> lines(type, Component.literal(text).withStyle(ChatFormatting.WHITE), wrap, 12);
            };
            rows.add(row);
            totalHeight += row.height();
        }
        lastMillis = Util.getMillis();
    }

    private Row lines(String type, Component text, int wrap, int lineHeight) {
        List<FormattedCharSequence> split = font.split(text, Math.max(40, wrap));
        return new Row(type, split, Math.max(1, split.size()) * lineHeight);
    }

    /** The credits text in the game language (German for any German locale), English otherwise. */
    private JsonArray load() {
        String lang = minecraft.getLanguageManager().getSelected().toLowerCase(Locale.ROOT);
        for (String file : lang.startsWith("de") ? List.of("de_de", "en_us") : List.of("en_us")) {
            ResourceLocation rl = ResourceLocation.fromNamespaceAndPath(OmaCore.MOD_ID, "texts/credits/" + file + ".json");
            Optional<Resource> res = minecraft.getResourceManager().getResource(rl);
            if (res.isEmpty()) {
                continue;
            }
            try (Reader reader = res.get().openAsReader()) {
                return JsonParser.parseReader(reader).getAsJsonObject().getAsJsonArray("lines");
            } catch (Exception e) {
                LOGGER.error("[oma_core] cannot read credits {}", rl, e);
            }
        }
        return new JsonArray();
    }

    @Override
    public void render(GuiGraphics g, int mouseX, int mouseY, float partialTick) {
        long now = Util.getMillis();
        float ticks = Math.min(10f, (now - lastMillis) / 50f); // real time, also smooth when the game is paused
        lastMillis = now;
        scroll += ticks * PIXELS_PER_TICK * (fastKey || fastMouse ? FAST : 1f);
        if (scroll > totalHeight + height + 40) {
            onClose();
            return;
        }
        g.fillGradient(0, 0, width, height, 0xFF2B1E14, 0xFF120B07);
        int center = width / 2;
        float y = height + 10 - scroll;
        for (Row row : rows) {
            if (y + row.height() >= 0 && y <= height) {
                draw(g, row, center, (int) y);
            }
            y += row.height();
        }
        g.drawCenteredString(font, Component.translatable("oma_core.credits.hint"), center, height - 12, 0x99FFFFFF);
    }

    private void draw(GuiGraphics g, Row row, int center, int y) {
        if (row.type().equals("logo")) {
            RenderSystem.enableBlend();
            g.blit(LOGO, center - LOGO_SIZE / 2, y, LOGO_SIZE, LOGO_SIZE, 0, 0, 256, 256, 256, 256);
            RenderSystem.disableBlend();
            return;
        }
        boolean big = row.type().equals("title");
        int lineHeight = row.text().isEmpty() ? 0 : row.height() / row.text().size();
        for (int i = 0; i < row.text().size(); i++) {
            FormattedCharSequence line = row.text().get(i);
            int ly = y + i * lineHeight;
            if (big) {
                g.pose().pushPose();
                g.pose().translate(center, ly, 0);
                g.pose().scale(2f, 2f, 1f);
                g.drawString(font, line, -font.width(line) / 2, 0, 0xFFFFFF, true);
                g.pose().popPose();
            } else {
                g.drawString(font, line, center - font.width(line) / 2, ly, 0xFFFFFF, true);
            }
        }
    }

    @Override
    public boolean keyPressed(int keyCode, int scanCode, int modifiers) {
        if (keyCode == GLFW.GLFW_KEY_SPACE) {
            fastKey = true;
            return true;
        }
        return super.keyPressed(keyCode, scanCode, modifiers);
    }

    @Override
    public boolean keyReleased(int keyCode, int scanCode, int modifiers) {
        if (keyCode == GLFW.GLFW_KEY_SPACE) {
            fastKey = false;
            return true;
        }
        return super.keyReleased(keyCode, scanCode, modifiers);
    }

    @Override
    public boolean mouseClicked(double mouseX, double mouseY, int button) {
        fastMouse = true;
        return true;
    }

    @Override
    public boolean mouseReleased(double mouseX, double mouseY, int button) {
        fastMouse = false;
        return true;
    }

    @Override
    public boolean isPauseScreen() {
        return false; // the music keeps playing; Grandma's kitchen is a safe place to stand
    }
}
